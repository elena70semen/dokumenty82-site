def section(title, intro, cards, eyebrow="", ident=""):
    items = []
    for i, (heading, body, href) in enumerate(cards, 1):
        tag = "a" if href else "article"
        attr = f' href="{href}"' if href else ""
        items.append(f'<{tag} class="glass-card rich-card"{attr}><span>{i:02}</span><h3>{heading}</h3><p>{body}</p></{tag}>')
    return f'''<section class="section page-rich-section"{f' id="{ident}"' if ident else ''}>
      <div class="section-header"><p class="eyebrow">{eyebrow}</p><h2>{title}</h2><p>{intro}</p></div>
      <div class="card-grid two rich-card-grid">{''.join(items)}</div>
    </section>'''


