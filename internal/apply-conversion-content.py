def main_sections(text):
    main = re.search(r'<main\b[^>]*>([\s\S]*?)</main>', text)
    if not main:
        raise ValueError("Missing main")
    return re.findall(r'<section\b[\s\S]*?</section>', main.group(1))


def replace_main(text, content):
    return re.sub(r'(<main\b[^>]*>)[\s\S]*?(</main>)', lambda m: m[1] + '\n' + content + '\n  ' + m[2], text, count=1)


def update(route, transform):
    p = ROOT / route / 'index.html'
    before = p.read_text(encoding='utf-8')
    after = transform(before)
    if after != before:
        p.write_text(after, encoding='utf-8', newline='\n')
        print(p.relative_to(ROOT).as_posix())


